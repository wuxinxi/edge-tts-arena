import assert from 'node:assert/strict'
import fs from 'node:fs'
import ts from 'typescript'
const compile = path => ts.transpileModule(fs.readFileSync(new URL(path, import.meta.url), 'utf8'), {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText
const dataUrl = source => 'data:text/javascript;base64,' + Buffer.from(source).toString('base64')
const metricUrl = dataUrl(compile('../src/chartMetrics.ts'))
const statsUrl = dataUrl(compile('../src/benchmarkStatistics.ts').replace("'./chartMetrics'", JSON.stringify(metricUrl)))
const {quantile,modelStatistics} = await import(statsUrl)
const {metricValue,relativePerformance,niceMaximum} = await import(metricUrl)
const run=(key,seconds,success=true)=>({model_key:key,model_name:key,success,metrics:success?{elapsed_time_sec:seconds,rtf:seconds/10,memory_peak_mb:seconds*100,memory_diff_mb:seconds*80,audio_duration_sec:10}:undefined})
assert.equal(quantile([5,1,3],.5),3)
assert.equal(quantile([9,1],.5),5)
assert.equal(quantile([], .5),null)
assert.equal(quantile([3], .9),3)
const stats=modelStatistics([run('a',1),run('a',9),run('a',0,false),run('b',5)],3)
assert.equal(stats[0].metricStats.elapsed_time_sec.median,5)
assert.deepEqual([stats[0].attempts,stats[0].success,stats[0].failed,stats[0].expected],[3,2,1,3])
assert.equal(stats[0].metricStats.elapsed_time_sec.min,1)
assert.equal(stats[0].metricStats.elapsed_time_sec.max,9)
assert.equal(stats[0].aggregate.metrics.rtf,.5)
assert.equal(stats[1].metricStats.elapsed_time_sec.count,1)
assert.equal(modelStatistics([run('a',0,false)],1)[0].aggregate,null)
const zero=modelStatistics([run('a',0)],1)[0]
assert.equal(zero.aggregate.metrics.elapsed_time_sec,0)
assert.equal(metricValue({metrics:{rtf:NaN}},'rtf'),null)
assert.equal(metricValue({metrics:{rtf:-1}},'rtf'),null)
assert.equal(metricValue({metrics:{}},'rtf'),null)
assert.equal(relativePerformance(4,[2,4]),.5)
assert.equal(relativePerformance(2,[2,2]),1)
assert.equal(relativePerformance(0,[0,4]),1)
assert.equal(relativePerformance(4,[0,4]),0)
assert.ok(niceMaximum(7.2)>=7.2)
assert.equal(modelStatistics([run('a',2),run('b',4)],{a:1,b:3})[1].expected,3)
assert.equal(modelStatistics([run('a',2)],{a:1})[0].expected,1)
console.log('22 项统计与图表边界检查通过。')
